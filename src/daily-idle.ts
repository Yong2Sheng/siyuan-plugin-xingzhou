function wrapIndex(index: number, length: number): number {
    const value = index % length;
    return value < 0 ? value + length : value;
}

export function idleLineAt(index: number): string {
    return IDLE_LINES[wrapIndex(index, IDLE_LINES.length)];
}

export function idleReactionAt(index: number): string {
    return IDLE_POKE_REACTIONS[wrapIndex(index, IDLE_POKE_REACTIONS.length)];
}

export function idleStickerFileAt(index: number): string {
    return IDLE_STICKER_FILES[wrapIndex(index, IDLE_STICKER_FILES.length)];
}
